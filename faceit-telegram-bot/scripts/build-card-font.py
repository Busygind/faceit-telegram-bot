"""Build the portable antialiased glyph atlas (development only; requires Pillow).

Source: DejaVu Sans 2.37, https://dejavu-fonts.github.io/.
License: docs/fonts/DejaVu-LICENSE.txt. Runtime never loads a font or filesystem.
"""

import base64
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parent.parent
FONT_SIZE = 64


def pack_rle(pixels):
    encoded = bytearray()
    index = 0
    while index < len(pixels):
        end = index + 1
        while end < len(pixels) and pixels[end] == pixels[index] and end - index < 255:
            end += 1
        encoded.extend((end - index, pixels[index]))
        index = end
    return base64.b64encode(encoded).decode("ascii")


def main():
    font = ImageFont.truetype(ROOT / "assets/fonts/DejaVuSans.ttf", FONT_SIZE)
    characters = set(chr(code) for code in range(32, 127))
    characters.update(chr(code) for code in range(160, 256))
    characters.update(chr(code) for code in range(0x400, 0x460))
    characters.update("—–…·№↑↓×≈✓")
    glyphs = {}
    for character in sorted(characters):
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        width, height = right - left, bottom - top
        image = Image.new("L", (max(1, width), max(1, height)))
        ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255, anchor="ls")
        glyphs[character] = [
            round(font.getlength(character), 4), left, top, width, height,
            pack_rle(image.tobytes()) if width and height else "",
        ]
    target = ROOT / "tgcloud/lib/card-font.js"
    target.write_text(
        "// Generated by scripts/build-card-font.py. Do not edit glyph data manually.\n"
        "// DejaVu Sans 2.37. License: docs/fonts/DejaVu-LICENSE.txt.\n"
        f"export const FONT_SIZE = {FONT_SIZE};\n"
        f"export const FONT_ASCENT = {font.getmetrics()[0]};\n"
        "export const GLYPHS = " + json.dumps(glyphs, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    print(f"Generated {len(glyphs)} glyphs in {target.name} ({target.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
